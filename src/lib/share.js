// 5. SOCIAL RESULT CARD (PNG via Canvas 2D) — for WhatsApp / Instagram
// ════════════════════════════════════════════════════════════════════════
export async function shareResultCardImage(match = {}, highlights = {}) {
  const S = 2; // retina scale
  const w = 1080, h = 1080; // square card for WhatsApp / Instagram
  const canvas = document.createElement('canvas');
  canvas.width = w * S; canvas.height = h * S;
  const ctx = canvas.getContext('2d');
  ctx.scale(S, S);

  const homeName = match?.home_team?.name || 'Home';
  const awayName = match?.away_team?.name || 'Away';
  const homeScore = match?.home_team?.score || '—';
  const awayScore = match?.away_team?.score || '—';
  const resultText = match?.resultText || match?.result_text || match?.result || 'Match Result';
  const tournament = match?.tournament || match?.stage || 'JDCA Fixture';
  const venue = match?.venue || '';

  // Background: navy gradient
  const g = ctx.createLinearGradient(0, 0, w, h);
  g.addColorStop(0, '#0B1628'); g.addColorStop(1, '#13233f');
  ctx.fillStyle = g; ctx.fillRect(0, 0, w, h);

  // Accent bar
  ctx.fillStyle = BRAND.blue; ctx.fillRect(0, 0, w, 14);

  const center = w / 2;
  const txt = (s, x, yy, { size = 40, weight = 'bold', color = '#fff', align = 'center', spacing } = {}) => {
    ctx.fillStyle = color;
    ctx.font = `${weight} ${size}px Helvetica, Arial, sans-serif`;
    ctx.textAlign = align; ctx.textBaseline = 'alphabetic';
    if (spacing) {
      // simple letter-spacing for the eyebrow label
      const chars = s.split(''); let cx = x - (measureSpaced(ctx, s, spacing) / 2);
      ctx.textAlign = 'left';
      for (const c of chars) { ctx.fillText(c, cx, yy); cx += ctx.measureText(c).width + spacing; }
      ctx.textAlign = align;
    } else {
      ctx.fillText(s, x, yy);
    }
  };

  // Logo
  const logo = await loadLogoDataUrl();
  if (logo) {
    try {
      const img = await loadImage(logo);
      ctx.drawImage(img, center - 70, 70, 140, 140);
    } catch { /* ignore */ }
  }

  txt('JABALPUR DIVISION CRICKET ASSOCIATION', center, 255, { size: 20, color: '#8FA6C8', spacing: 3 });
  txt(fit(ctx, tournament.toUpperCase(), 900, 26, 'bold'), center, 300, { size: 26, color: '#5B8DEF' });

  // Teams + scores
  txt(fit(ctx, homeName, 960, 52, 'bold'), center, 430, { size: 52, color: '#fff' });
  txt(homeScore, center, 500, { size: 62, color: '#9DBFF5', weight: 'bold' });

  txt('VS', center, 570, { size: 28, color: '#64748B' });

  txt(fit(ctx, awayName, 960, 52, 'bold'), center, 660, { size: 52, color: '#fff' });
  txt(awayScore, center, 730, { size: 62, color: '#9DBFF5', weight: 'bold' });

  // Result pill
  const rLines = wrapText(ctx, resultText, 900, 34, 'bold');
  const pillH = 40 + rLines.length * 44;
  const pillY = 790;
  roundRect(ctx, center - 460, pillY, 920, pillH, 18);
  ctx.fillStyle = BRAND.blue; ctx.fill();
  rLines.forEach((ln, i) => txt(ln, center, pillY + 54 + i * 44, { size: 34, color: '#fff' }));

  // Highlights
  let hy = pillY + pillH + 70;
  const tb = highlights?.topBatter, tbow = highlights?.topBowler;
  if (tb?.name) { txt('TOP BATTER', center - 230, hy, { size: 18, color: '#64748B', spacing: 2 }); txt(fit(ctx, tb.name, 420, 30, 'bold'), center - 230, hy + 38, { size: 30, color: '#fff' }); }
  if (tbow?.name) { txt('TOP BOWLER', center + 230, hy, { size: 18, color: '#64748B', spacing: 2 }); txt(fit(ctx, tbow.name, 420, 30, 'bold'), center + 230, hy + 38, { size: 30, color: '#fff' }); }

  if (venue) txt(fit(ctx, venue, 960, 22), center, h - 40, { size: 22, color: '#64748B', weight: 'normal' });

  const blob = await new Promise((resolve) => canvas.toBlob(resolve, 'image/png', 0.95));
  if (!blob) throw new Error('Could not render result card');
  return shareOrDownload(blob, `result-${slug(homeName)}-vs-${slug(awayName)}.png`, {
    title: `${homeName} vs ${awayName}`,
    text: resultText,
  });
}

// ── tiny helpers ────────────────────────────────────────────────────────
const n = (v) => (v === 0 || v ? String(v) : '0');

function resolveMotmName(scorecard, match) {
  const cands = [scorecard?.manOfTheMatch, scorecard?.man_of_the_match, scorecard?.playerOfMatch, match?.man_of_the_match, match?.playerOfMatch];
  for (const c of cands) {
    if (!c) continue;
    const v = Array.isArray(c) ? c[0] : c;
    if (typeof v === 'string' && v.trim()) return v.trim();
    if (v?.full_name || v?.name) return v.full_name || v.name;
  }
  return null;
}

function loadImage(src) {
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.onload = () => resolve(img);
    img.onerror = reject;
    img.src = src;
  });
}
function measureSpaced(ctx, s, spacing) {
  let total = 0;
  for (const c of s) total += ctx.measureText(c).width + spacing;
  return total - spacing;
}
function roundRect(ctx, x, y, w, h, r) {
  ctx.beginPath();
  ctx.moveTo(x + r, y);
  ctx.arcTo(x + w, y, x + w, y + h, r);
  ctx.arcTo(x + w, y + h, x, y + h, r);
  ctx.arcTo(x, y + h, x, y, r);
  ctx.arcTo(x, y, x + w, y, r);
  ctx.closePath();
}
// shrink font until the text fits maxWidth; returns the (possibly unchanged) text
function fit(ctx, text, maxWidth, size, weight = 'bold') {
  ctx.font = `${weight} ${size}px Helvetica, Arial, sans-serif`;
  let t = String(text || '');
  if (ctx.measureText(t).width <= maxWidth) return t;
  while (t.length > 4 && ctx.measureText(t + '…').width > maxWidth) t = t.slice(0, -1);
  return t + '…';
}
function wrapText(ctx, text, maxWidth, size, weight = 'bold') {
  ctx.font = `${weight} ${size}px Helvetica, Arial, sans-serif`;
  const words = String(text || '').split(/\s+/);
  const lines = []; let line = '';
  for (const word of words) {
    const test = line ? line + ' ' + word : word;
    if (ctx.measureText(test).width > maxWidth && line) { lines.push(line); line = word; }
    else line = test;
  }
  if (line) lines.push(line);
  return lines.slice(0, 3);
}
