// Central sharing/export module for JDCA.
//
// Produces REAL files (not screenshots):
//   • Scorecard, Teams roster, and Points table as designed PDFs (jsPDF + autotable)
//   • Match result as a branded PNG card for WhatsApp / Instagram (Canvas 2D)
//
// jsPDF is lazy-loaded so it never enters the initial bundle — it only loads
// the first time a user taps Share/Download. Everything works offline once the
// chunk + logo are cached by the service worker.

// ── Brand palette (JDCA v3) ─────────────────────────────────────────────
export const BRAND = {
  navy: '#0B1628',
  blue: '#1D4ED8',
  bg: '#F0F4F8',
  ink: '#1E293B',
  grey: '#64748B',
  line: '#E2E8F0',
  white: '#FFFFFF',
  green: '#15803D',
  red: '#DC2626',
  amber: '#B45309',
};

const hexToRgb = (h) => {
  const n = parseInt(h.replace('#', ''), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
};

// ── Logo cache (fetched from same origin, SW-cached) ────────────────────
let _logoPromise = null;
function loadLogoDataUrl() {
  if (_logoPromise) return _logoPromise;
  _logoPromise = (async () => {
    try {
      const res = await fetch('/jdca-logo.png');
      if (!res.ok) return null;
      const blob = await res.blob();
      return await new Promise((resolve) => {
        const r = new FileReader();
        r.onloadend = () => resolve(r.result);
        r.onerror = () => resolve(null);
        r.readAsDataURL(blob);
      });
    } catch {
      return null;
    }
  })();
  return _logoPromise;
}

let _jspdfPromise = null;
async function loadJsPDF() {
  if (!_jspdfPromise) {
    _jspdfPromise = (async () => {
      const [{ jsPDF }, autoTableMod] = await Promise.all([
        import('jspdf'),
        import('jspdf-autotable'),
      ]);
      const autoTable = autoTableMod.default || autoTableMod.autoTable;
      return { jsPDF, autoTable };
    })();
  }
  return _jspdfPromise;
}

// ── Universal "share a file, else download it" ──────────────────────────
// Uses the Web Share API with files where supported (mobile), otherwise
// falls back to a normal download. Never throws on a user cancel.
export async function shareOrDownload(blob, filename, { title, text, forceDownload } = {}) {
  const file = new File([blob], filename, { type: blob.type });
  try {
    if (!forceDownload && navigator.canShare && navigator.canShare({ files: [file] })) {
      await navigator.share({ files: [file], title, text });
      return 'shared';
    }
  } catch (err) {
    // AbortError = user dismissed the sheet. Treat as handled, don't fall back.
    if (err && err.name === 'AbortError') return 'cancelled';
  }
  // Fallback: trigger a download
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 4000);
  return 'downloaded';
}

const slug = (s) => String(s || 'jdca').replace(/[^a-z0-9]+/gi, '-').replace(/^-|-$/g, '').toLowerCase();

// ── Shared PDF chrome (header band + footer) ────────────────────────────
async function paintHeader(doc, { title, subtitle }) {
  const W = doc.internal.pageSize.getWidth();
  doc.setFillColor(...hexToRgb(BRAND.navy));
  doc.rect(0, 0, W, 86, 'F');

  const logo = await loadLogoDataUrl();
  if (logo) {
    try { doc.addImage(logo, 'PNG', 40, 20, 46, 46); } catch { /* ignore */ }
  }
  const x = logo ? 100 : 40;
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.text('JABALPUR DIVISION CRICKET ASSOCIATION', x, 32);
  doc.setFontSize(17);
  doc.text(title, x, 54);
  if (subtitle) {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9.5);
    doc.setTextColor(176, 190, 210);
    doc.text(subtitle, x, 71);
  }
}

function paintFooter(doc) {
  const W = doc.internal.pageSize.getWidth();
  const H = doc.internal.pageSize.getHeight();
  const pages = doc.internal.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    doc.setDrawColor(...hexToRgb(BRAND.line));
    doc.setLineWidth(0.7);
    doc.line(40, H - 34, W - 40, H - 34);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(...hexToRgb(BRAND.grey));
    doc.text('Generated by the official JDCA Scoring App', 40, H - 20);
    doc.text(`Page ${i} of ${pages}`, W - 40, H - 20, { align: 'right' });
    const stamp = new Date().toLocaleString('en-IN', { dateStyle: 'medium', timeStyle: 'short' });
    doc.text(stamp, W / 2, H - 20, { align: 'center' });
  }
}

function sectionTitle(doc, text, y) {
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(...hexToRgb(BRAND.navy));
  doc.text(text, 40, y);
  return y + 6;
}

const tableTheme = (headColor = BRAND.navy) => ({
  theme: 'grid',
  margin: { left: 40, right: 40 },
  styles: { font: 'helvetica', fontSize: 8.5, cellPadding: 5, textColor: hexToRgb(BRAND.ink), lineColor: hexToRgb(BRAND.line), lineWidth: 0.5 },
  headStyles: { fillColor: hexToRgb(headColor), textColor: [255, 255, 255], fontStyle: 'bold', fontSize: 8.5, halign: 'left' },
  alternateRowStyles: { fillColor: hexToRgb(BRAND.bg) },
});

